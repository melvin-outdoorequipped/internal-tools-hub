# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
UPC_ALIASES = ["upc", "upc/ean", "ean", "upc code", "barcode", "product id",
               "external_product_id", "external product id", "gtin"]
SKU_ALIASES = ["seller-sku", "seller sku", "sku", "item_sku", "item sku",
               "merchant sku", "sku id"]
ASIN_ALIASES = ["asin1", "asin", "asin 1", "asin-1"]


def norm(val) -> str:
    """Lowercase, trim, collapse whitespace/nbsp. NaN -> ''."""
    if val is None or (not isinstance(val, str) and pd.isna(val)):
        return ""
    return re.sub(r"\s+", " ", str(val).replace("\xa0", " ")).strip().lower()


def clean_key(val) -> str:
    """Clean SKU / ASIN keys (case-insensitive matching)."""
    s = norm(val).upper()
    return "" if s in ("", "NAN", "NONE", "NULL") else s


def clean_upc(val) -> str:
    """Return a clean digits-only UPC/EAN, or '' if not valid."""
    s = norm(val)
    if s in ("", "nan", "none", "null"):
        return ""
    # Scientific notation, e.g. 8.13385E+11
    if re.fullmatch(r"\d+(\.\d+)?e\+?\d+", s):
        try:
            s = str(int(float(s)))
        except Exception:
            return ""
    s = re.sub(r"\.0+$", "", s)       # 123.0 -> 123
    s = re.sub(r"\D", "", s)          # keep digits only
    if len(s) == 11:                  # Excel dropped a leading zero
        s = s.zfill(12)
    return s if 8 <= len(s) <= 14 else ""


def dedupe_headers(headers):
    """Make column names unique so df[col] is always a Series."""
    seen, out = {}, []
    for h in headers:
        h = h if h else "unnamed_col"
        if h in seen:
            seen[h] += 1
            out.append(f"{h}__{seen[h]}")
        else:
            seen[h] = 0
            out.append(h)
    return out


def first_match(columns, aliases):
    for a in aliases:
        if a in columns:
            return a
    return None


def find_header_row(df_raw, max_rows=30):
    """Find the first row that has a UPC column plus a SKU or ASIN column."""
    for i in range(min(max_rows, len(df_raw))):
        vals = {norm(v) for v in df_raw.iloc[i].values}
        has_upc = any(a in vals for a in UPC_ALIASES)
        has_key = any(a in vals for a in SKU_ALIASES + ASIN_ALIASES)
        if has_upc and has_key:
            return i
    return None


def read_file_to_sheets(file):
    """Return {sheet_name: raw DataFrame (no header)}."""
    file.seek(0)
    name = file.name.lower()
    if name.endswith(".csv"):
        for enc in ("utf-8-sig", "latin-1"):
            try:
                file.seek(0)
                df = pd.read_csv(file, dtype=str, header=None, encoding=enc,
                                 on_bad_lines="skip", engine="python")
                return {"CSV": df}
            except UnicodeDecodeError:
                continue
        raise ValueError("Could not decode CSV")
    return pd.read_excel(file, sheet_name=None, dtype=str, header=None)


def read_missing_file(file) -> pd.DataFrame:
    """Read the Missing SKUs file from CSV or Excel (first sheet)."""
    file.seek(0)
    name = file.name.lower()
    if name.endswith(".csv"):
        try:
            return pd.read_csv(file, dtype=str, encoding="utf-8-sig")
        except UnicodeDecodeError:
            file.seek(0)
            return pd.read_csv(file, dtype=str, encoding="latin-1")
    # Excel (.xlsx / .xls) — first sheet, everything as text
    return pd.read_excel(file, dtype=str, sheet_name=0)


# ---------------------------------------------------------------------------
# UI
# ---------------------------------------------------------------------------
st.markdown("### 1. Upload Missing SKUs File")
st.info("Upload the file generated by the SKU Gap Finder (missing_skus.csv or missing_skus.xlsx).")
file_missing = st.file_uploader(
    "Upload Missing SKUs (CSV or Excel)",
    type=["csv", "xlsx", "xls"],
    key="upc_missing",
)

st.markdown("### 2. Upload Amazon Listing Files")
st.info("Upload one or multiple Amazon Listing Excel/CSV files. The tool will scan ALL tabs to find the correct data.")
files_listing = st.file_uploader(
    "Upload Listing Files",
    type=["xlsx", "xls", "csv"],
    accept_multiple_files=True,
    key="upc_listings",
)

if st.button("🔎 Gather UPCs", type="primary", use_container_width=True):
    if not file_missing or not files_listing:
        st.warning("⚠️ Please upload both the Missing SKUs file and at least one Amazon Listing file.")
    else:
        with st.spinner("Scanning tabs and building UPC database..."):
            try:
                # -----------------------------------------------------------
                # 1. Load & clean Missing SKUs (CSV or Excel)
                # -----------------------------------------------------------
                df_missing = read_missing_file(file_missing)
                df_missing.columns = dedupe_headers([norm(c).upper() for c in df_missing.columns])

                if "SKU" not in df_missing.columns and "ASIN" not in df_missing.columns:
                    st.error("❌ Missing SKUs file must contain 'SKU' or 'ASIN' columns.")
                    st.stop()

                # ---------------------------------------------------------
                # 2. Build lookup dictionaries from every tab of every file
                # ---------------------------------------------------------
                sku_to_upc, asin_to_upc = {}, {}
                scan_log = []

                for file in files_listing:
                    try:
                        sheets = read_file_to_sheets(file)
                    except Exception as e:
                        st.warning(f"Could not read {file.name}: {e}")
                        continue

                    for sheet_name, df_raw in sheets.items():
                        if df_raw is None or df_raw.empty or len(df_raw) < 2:
                            continue

                        header_idx = find_header_row(df_raw)
                        if header_idx is None:
                            scan_log.append(f"{file.name} → '{sheet_name}': no header row found (skipped)")
                            continue

                        headers = dedupe_headers([norm(c) for c in df_raw.iloc[header_idx].values])
                        df_data = df_raw.iloc[header_idx + 1:].copy()
                        df_data.columns = headers

                        upc_col = first_match(headers, UPC_ALIASES)
                        sku_col = first_match(headers, SKU_ALIASES)
                        asin_col = first_match(headers, ASIN_ALIASES)
                        if not upc_col:
                            continue

                        # Positional access -> always 1-D Series, never a DataFrame
                        upcs = df_data[upc_col].map(clean_upc)
                        skus = df_data[sku_col].map(clean_key) if sku_col else None
                        asins = df_data[asin_col].map(clean_key) if asin_col else None

                        added = 0
                        for idx in range(len(df_data)):
                            u = upcs.iloc[idx]
                            if not u:
                                continue
                            if skus is not None:
                                k = skus.iloc[idx]
                                if k and k not in sku_to_upc:
                                    sku_to_upc[k] = u
                                    added += 1
                            if asins is not None:
                                k = asins.iloc[idx]
                                if k and k not in asin_to_upc:
                                    asin_to_upc[k] = u
                        scan_log.append(f"{file.name} → '{sheet_name}': header row {header_idx + 1}, {added:,} SKUs read")

                if scan_log:
                    with st.expander("📄 Scan details (files / tabs read)"):
                        for line in scan_log:
                            st.write(line)

                if not sku_to_upc and not asin_to_upc:
                    st.error("❌ Could not find any valid UPCs in any tab of the uploaded files.")
                else:
                    st.success(f"✅ Database built! Found {len(sku_to_upc):,} SKU matches and {len(asin_to_upc):,} ASIN matches.")

                    # -------------------------------------------------------
                    # 3. Lookup
                    # -------------------------------------------------------
                    found_upcs, match_types = [], []
                    for _, row in df_missing.iterrows():
                        sku = clean_key(row.get("SKU", ""))
                        asin = clean_key(row.get("ASIN", ""))
                        if sku and sku in sku_to_upc:
                            found_upcs.append(sku_to_upc[sku])
                            match_types.append("✅ SKU Match")
                        elif asin and asin in asin_to_upc:
                            found_upcs.append(asin_to_upc[asin])
                            match_types.append("✅ ASIN Match")
                        else:
                            found_upcs.append("")
                            match_types.append("❌ Not Found")

                    df_missing["Found UPC"] = found_upcs
                    df_missing["Match Type"] = match_types

                    # -------------------------------------------------------
                    # 4. Results
                    # -------------------------------------------------------
                    total = len(df_missing)
                    found_count = int((df_missing["Found UPC"] != "").sum())
                    missing_count = total - found_count

                    col1, col2, col3 = st.columns(3)
                    col1.metric("Total SKUs Checked", f"{total:,}")
                    col2.metric("UPCs Found", f"{found_count:,}")
                    col3.metric("UPCs Missing", f"{missing_count:,}")

                    st.markdown("<br>", unsafe_allow_html=True)
                    df_display = df_missing.sort_values(by="Match Type", ascending=True)
                    st.dataframe(df_display, use_container_width=True, hide_index=True)

                    # -------------------------------------------------------
                    # 5. Downloads (CSV + Excel)
                    # -------------------------------------------------------
                    dl_col1, dl_col2 = st.columns(2)

                    # CSV — tab-prefix forces Excel to treat UPC as text
                    out_csv = df_missing.copy()
                    out_csv["Found UPC"] = out_csv["Found UPC"].apply(
                        lambda x: f"\t{x}" if x else ""
                    )
                    with dl_col1:
                        st.download_button(
                            label="⬇️ Download as CSV",
                            data=out_csv.to_csv(index=False).encode("utf-8-sig"),
                            file_name="missing_skus_with_upcs.csv",
                            mime="text/csv",
                            type="primary",
                            use_container_width=True,
                        )

                    # Excel — UPC column formatted as Text ("@") so no 8.13E+11
                    buf = io.BytesIO()
                    with pd.ExcelWriter(buf, engine="openpyxl") as writer:
                        df_missing.to_excel(writer, index=False, sheet_name="Missing SKUs")
                        ws = writer.sheets["Missing SKUs"]
                        upc_col_idx = list(df_missing.columns).index("Found UPC") + 1
                        for row in range(2, len(df_missing) + 2):
                            ws.cell(row=row, column=upc_col_idx).number_format = "@"
                    with dl_col2:
                        st.download_button(
                            label="⬇️ Download as Excel",
                            data=buf.getvalue(),
                            file_name="missing_skus_with_upcs.xlsx",
                            mime="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                            use_container_width=True,
                        )

            except Exception as e:
                st.error(f"❌ Error processing files: {e}")